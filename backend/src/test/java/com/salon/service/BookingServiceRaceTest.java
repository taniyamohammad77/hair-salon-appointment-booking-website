package com.salon.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyInt;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.util.List;
import java.util.Optional;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;

import com.salon.dto.BookingRequest;
import com.salon.dto.RescheduleRequest;
import com.salon.entity.BookingEntity;
import com.salon.entity.BookingStatus;
import com.salon.exception.ApiException;
import com.salon.repository.BookingRepository;
import com.salon.repository.ServiceRepository;
import com.salon.repository.StylistRepository;

/**
 * Unit tests for the empty-target-day race (Trap 3 remainder):
 *
 * The pessimistic lock only locks EXISTING rows. When the target date has no
 * bookings yet, two concurrent requests can both pass the availability
 * re-check and the loser dies at UQ_bookings_slot as a
 * DataIntegrityViolationException. These tests prove the service translates
 * that into the same friendly 409 as the re-check — never a raw 500.
 *
 * The stale-re-check scenario is simulated by mocking the availability engine
 * to report the slot free while the repository (i.e. the DB) rejects the write.
 */
class BookingServiceRaceTest {

	private static final Long STYLIST = 1L;
	private static final Long SERVICE = 1L;
	private static final LocalDate FUTURE_DATE = LocalDate.now().plusDays(30);

	private BookingRepository bookingRepository;
	private AvailabilityService availabilityService;
	private BookingService bookingService;

	@BeforeEach
	void setUp() {
		bookingRepository = mock(BookingRepository.class);
		availabilityService = mock(AvailabilityService.class);
		bookingService = new BookingService(
				bookingRepository,
				availabilityService,
				mock(ServiceRepository.class),
				mock(StylistRepository.class));
	}

	private BookingEntity confirmedBookingAt(LocalTime time) {
		BookingEntity b = new BookingEntity();
		// id stays null (no setter — generated by the DB); the service never
		// relies on it in these paths (the exclusion check is mocked away).
		b.setServiceId(SERVICE);
		b.setStylistId(STYLIST);
		b.setBookingDate(FUTURE_DATE);
		b.setBookingTime(time);
		b.setEndTime(time.plusMinutes(55));
		b.setStatus(BookingStatus.CONFIRMED);
		b.setCustomerName("Test Customer");
		b.setPhone("0700000000");
		b.setEmail("slotmath@example.com");
		return b;
	}

	private void slotLooksFree(LocalTime start) {
		when(availabilityService.validateAndLoadServiceDuration(SERVICE, STYLIST)).thenReturn(55);
		when(availabilityService.computeFreeSlots(any(), any(), anyInt(), any(), any()))
				.thenReturn(List.of(new AvailabilityService.Slot(start, start.plusMinutes(55))));
	}

	@Test
	@DisplayName("reschedule: DB rejects the flushed update → 409, not 500")
	void rescheduleLostRace_returns409() {
		BookingEntity booking = confirmedBookingAt(LocalTime.of(11, 0));
		when(bookingRepository.findById(42L)).thenReturn(Optional.of(booking));
		slotLooksFree(LocalTime.of(14, 0));
		when(bookingRepository.saveAndFlush(any(BookingEntity.class)))
				.thenThrow(new DataIntegrityViolationException("UQ_bookings_slot violation"));

		// PHASE 5A: owner param — the booking's own verified account here.
		assertThatThrownBy(() -> bookingService.rescheduleBooking(42L,
				new RescheduleRequest(FUTURE_DATE, LocalTime.of(14, 0)),
				new BookingService.BookingOwner("slotmath@example.com", true, LocalDateTime.now().minusDays(1))))
				.isInstanceOf(ApiException.class)
				.satisfies(ex -> assertThat(((ApiException) ex).getStatus().value()).isEqualTo(409))
				.hasMessage("This time slot is no longer available.");
	}

	@Test
	@DisplayName("reschedule: DB accepts the update → 200 with recomputed end time")
	void rescheduleHappyPath_stillWorks() {
		BookingEntity booking = confirmedBookingAt(LocalTime.of(11, 0));
		when(bookingRepository.findById(42L)).thenReturn(Optional.of(booking));
		slotLooksFree(LocalTime.of(14, 0));
		when(bookingRepository.saveAndFlush(any(BookingEntity.class))).thenReturn(booking);

		var response = bookingService.rescheduleBooking(42L,
				new RescheduleRequest(FUTURE_DATE, LocalTime.of(14, 0)),
				new BookingService.BookingOwner("slotmath@example.com", true, LocalDateTime.now().minusDays(1)));

		assertThat(response.time()).isEqualTo(LocalTime.of(14, 0));
		assertThat(response.endTime()).isEqualTo(LocalTime.of(14, 55));
	}

	@Test
	@DisplayName("create: DB rejects the insert → 409, not 500 (empty-day race)")
	void createLostRace_returns409() {
		slotLooksFree(LocalTime.of(10, 0));
		when(bookingRepository.save(any(BookingEntity.class)))
				.thenThrow(new DataIntegrityViolationException("UQ_bookings_slot violation"));

		BookingRequest req = new BookingRequest(SERVICE, STYLIST, FUTURE_DATE, LocalTime.of(10, 0),
				"Test Customer", "0700000000", "slotmath@example.com", null);

		assertThatThrownBy(() -> bookingService.createBooking(req,
				new BookingService.BookingOwner("slotmath@example.com", true, LocalDateTime.now().minusDays(1))))
				.isInstanceOf(ApiException.class)
				.satisfies(ex -> assertThat(((ApiException) ex).getStatus().value()).isEqualTo(409))
				.hasMessage("This time slot is no longer available.");
	}
}
